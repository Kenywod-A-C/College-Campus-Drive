"""Regenerates docs/API_CONTRACT.md from the Flask URL map (implemented) and the frontend mock call sites (still mock-only).

    cd backend && python scripts/gen_api_contract.py
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from app import create_app  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")


def main() -> None:
    app = create_app("testing")
    impl = set()
    for r in app.url_map.iter_rules():
        if r.rule.startswith("/api/v1"):
            path = re.sub(r"<(?:\w+:)?(\w+)>", r"{\1}", r.rule[len("/api/v1"):])
            impl.update((m, path) for m in r.methods - {"HEAD", "OPTIONS"})
    norm = lambda p: re.sub(r"\{\w+\}", "{id}", p)  # noqa: E731
    impl_n = {(m, norm(p)) for m, p in impl}

    mock = set()
    for f in glob.glob(os.path.join(ROOT, "src/services/mock/*.ts")):
        src = open(f).read()
        # 1) call('METHOD', '/path') and 2) call('METHOD', cond ? `/a` : '/b') — collect every quoted path in the 2nd argument
        for m in re.finditer(r"call\(\s*'([A-Z]+)',\s*((?:[^,()]|\([^)]*\))+?)\s*,\s*\(", src):
            for q in re.finditer(r"[`']((?:/)[^`']*)[`']", m.group(2)):
                mock.add((m.group(1), re.sub(r"\$\{[^}]+\}", "{id}", q.group(1))))
    # the mock edits with POST /x/{id}; the real API uses PUT /x/{id} for the same operation
    covered = lambda m, p: (m, norm(p)) in impl_n or (m == "POST" and p.rstrip("/").split("/")[-1].startswith("{") and ("PUT", norm(p)) in impl_n)  # noqa: E731
    todo = sorted(x for x in mock if not covered(*x))

    md = ("# REST contract: implementation status\n\nGenerated by `backend/scripts/gen_api_contract.py` from the Flask URL map and the frontend mock. "
          "Conventions (envelopes, errors, auth, pagination): [API_CONVENTIONS.md](API_CONVENTIONS.md). Base path `/api/v1`.\n\n")
    md += (f"## Implemented by the Flask backend ({len(impl)} endpoints)\nThese are tested (pytest on SQLite and MySQL/MariaDB) and used by the frontend "
           "when `VITE_USE_MOCK` is not `true`.\n\n| Method | Path |\n|---|---|\n")
    md += "".join(f"| {m} | `{p}` |\n" for m, p in sorted(impl, key=lambda x: (x[1], x[0])))
    md += (f"\n## Not implemented yet ({len(todo)} endpoints, mock only)\nIn real mode the frontend shows an honest *\"Not available yet\"* state (HTTP 501); "
           "it never silently falls back to mock data.\n\n| Method | Path |\n|---|---|\n")
    md += "".join(f"| {m} | `{p}` |\n" for m, p in todo)
    open(os.path.join(ROOT, "docs/API_CONTRACT.md"), "w").write(md)
    print(f"{len(impl)} implemented, {len(todo)} mock-only")


if __name__ == "__main__":
    main()
